import type { ProjectMode } from '@/types';

/**
 * Описание режима работы — один источник на все места, где о режимах
 * рассказывают: экран выбора при входе и список в «Настройках».
 *
 * Раньше подписи и пояснения лежали в `SettingsPage` рядом с разметкой,
 * и на экране входа стояла своя, третья формулировка. Режим выбирают
 * один раз и надолго, и два разных объяснения одного и того же — это
 * два разных обещания.
 */
export type WorkModeInfo = {
  value: ProjectMode;
  label: string;
  /** Одной строкой — для строки списка, где места на абзац нет. */
  summary: string;
  /**
   * Чем режим отличается **от другого** — для экрана выбора при входе.
   *
   * Только различия и ничего сверх них. Раньше в пунктах стояли печать,
   * чертёж и выгрузка — вещи сами по себе верные, но общие для обоих
   * режимов или спорные, и человек, читая их, не мог понять, чем один
   * выбор отличается от второго: печать вроде бы и там и там, чертёж
   * тоже. Всё, что не различает, из списка убрано.
   *
   * Три коротких строки, а не абзац на каждый: карточку на экране входа
   * не читают, а проглядывают.
   */
  points: string[];
};

/**
 * Строки-сводки нарочно построены одинаково и расходятся в одном:
 * вводит числа расчёта человек или они подставляются сами. Это и есть
 * разница между режимами — всё остальное следует из неё.
 *
 * Формулировки выверены по коду, а не написаны «в общем». В инженерном
 * режиме из каталога приходит ровно одна величина — диаметр основания
 * (`applyCrusherToGeom`), остальные поля открываются значениями методики
 * и правятся руками; в упрощённом из каталога берутся диаметр и щель
 * (`deriveGeomFromCrusher`), остальное — та же методика, но полей ввода
 * пользователь не видит вовсе. Поэтому здесь нет ни «ни одно значение
 * не подставляется за вас» (подставляется — диаметр), ни «числа берутся
 * из справочника» (из справочника приходят два числа из дюжины).
 */
export const WORK_MODES: WorkModeInfo[] = [
  {
    value: 'engineering',
    label: 'Инженерный',
    summary: 'Числа расчёта вводите вы.',
    points: [
      'Геометрия камеры набирается поле за полем',
      'Из каталога приходит только диаметр машины',
      'Одна дробилка и одна проба руды на проект',
    ],
  },
  {
    value: 'simplified',
    label: 'Упрощённый',
    summary: 'Числа расчёта подставляются сами.',
    points: [
      'Дробилка и проба подбираются по параметрам',
      'Вручную — только крупность продукта',
      'Дробилок и проб можно отметить несколько',
    ],
  },
];

export function workMode(value: ProjectMode): WorkModeInfo {
  return WORK_MODES.find((m) => m.value === value) ?? WORK_MODES[0];
}

