import type { ProjectMode } from '@/types';

/**
 * Описание режима работы — один источник на все места, где о режимах
 * рассказывают: экран выбора при входе и список в «Настройках».
 *
 * Раньше подписи и пояснения лежали в `SettingsPage` рядом с разметкой,
 * и на экране входа стояла своя, третья формулировка. Режим выбирают
 * один раз и надолго, и два разных объяснения одного и того же — это
 * два разных обещания.
 */
export type WorkModeInfo = {
  value: ProjectMode;
  label: string;
  /** Одной строкой — для строки списка, где места на абзац нет. */
  summary: string;
  /**
   * Что режим даёт по пунктам — для экрана выбора при входе.
   *
   * Три коротких строки, а не абзац на каждый: карточку на экране входа
   * не читают, а проглядывают, и четыре строки с переносами превращали
   * выбор из двух вариантов в страницу текста. Порядок повторяет
   * порядок шагов расчёта.
   */
  points: string[];
};

export const WORK_MODES: WorkModeInfo[] = [
  {
    value: 'engineering',
    label: 'Инженерный',
    summary: 'Ручная настройка всех параметров на каждом этапе.',
    points: ['Геометрия камеры — поле за полем', 'Чертёж камеры и таблица профиля', 'Печать, Excel и КОМПАС-3D'],
  },
  {
    value: 'simplified',
    label: 'Упрощённый',
    summary: 'Три коротких шага и готовый отчёт.',
    points: ['Дробилки и пробы — по параметрам', 'Можно отметить несколько сразу', 'Ручной ввод — только крупность продукта'],
  },
];

export function workMode(value: ProjectMode): WorkModeInfo {
  return WORK_MODES.find((m) => m.value === value) ?? WORK_MODES[0];
}

