import type { ProjectMode } from '@/types';

/**
 * Описание режима работы — один источник на все места, где о режимах
 * рассказывают: экран выбора при входе и список в «Настройках».
 *
 * Раньше подписи и пояснения лежали в `SettingsPage` рядом с разметкой,
 * и на экране входа стояла своя, третья формулировка. Режим выбирают
 * один раз и надолго, и два разных объяснения одного и того же — это
 * два разных обещания.
 */
export type WorkModeInfo = {
  value: ProjectMode;
  label: string;
  /** Одной строкой — для строки списка, где места на абзац нет. */
  summary: string;
  /**
   * Чем режим отличается **от другого** — для экрана выбора при входе.
   *
   * Только различия и ничего сверх них. Раньше в пунктах стояли печать,
   * чертёж и выгрузка — вещи сами по себе верные, но общие для обоих
   * режимов или спорные, и человек, читая их, не мог понять, чем один
   * выбор отличается от второго: печать вроде бы и там и там, чертёж
   * тоже. Всё, что не различает, из списка убрано.
   *
   * Три коротких строки, а не абзац на каждый: карточку на экране входа
   * не читают, а проглядывают.
   */
  points: string[];
};

/**
 * Сводки построены одинаково и расходятся в одном: данные расчёта
 * редактирует человек или они составляются сами. Это и есть разница
 * между режимами — всё остальное следует из неё.
 *
 * Последний пункт у обоих одинаковый намеренно: отчёт по выбранным
 * параметрам получается в любом режиме, и умолчать об этом в одной
 * из карточек значило бы намекнуть, что где-то его нет.
 */
export const WORK_MODES: WorkModeInfo[] = [
  {
    value: 'engineering',
    label: 'Инженерный',
    summary: 'Данные расчёта редактируются вручную',
    points: [
      'Геометрия дробилки и характеристический грансостав редактируются вручную',
      'Одна дробилка и пробы руды на проект',
      'Итоговый отчёт по выбранным параметрам',
    ],
  },
  {
    value: 'simplified',
    label: 'Упрощённый',
    summary: 'Данные расчёта составляются автоматически',
    points: [
      'Дробилка и проба подбираются по параметрам',
      'Одна или несколько дробилок и пробы руды на проект',
      'Итоговый отчёт по выбранным параметрам',
    ],
  },
];

export function workMode(value: ProjectMode): WorkModeInfo {
  return WORK_MODES.find((m) => m.value === value) ?? WORK_MODES[0];
}
