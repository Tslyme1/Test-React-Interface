export type UserRole = 'Инженер' | 'Администратор + инженер';

export type User = {
  login: string;
  password: string;
  name: string;
  email: string;
  role: UserRole;
};

export type AngleUnit = 'deg' | 'рад';

/** Число зон дробления профиля камеры — одна ступень или две. */
export type ZoneCount = '1' | '2';

/**
 * Параметры шага «Геометрия камеры дробления» — полная цепочка профиля,
 * та же, что строит схема (`ChamberScheme`) и что задавал прототип-источник
 * (`legacy-prototype/uploads/cone-crusher-chamber.html`, объект `st`).
 *
 * Имена полей повторяют подписи на самом чертеже: `b40` — это угол β₄₀
 * у точки 40, `l11` — сегмент l₁₁ между точками 40 и 41. Совпадение имён
 * с чертежом здесь не косметика: по этим же ключам связаны участок схемы
 * и поле формы (наведение на одно подсвечивает другое).
 *
 * ⚠️ Длины двух броней различаются РЕГИСТРОМ первой буквы, как и на чертеже:
 * строчная `l11`/`l12`/`l1i`/`l2` — броня чаши, прописная `L10`/`L11`/`L12`/`L1i`
 * — броня конуса. `l12` и `L12` — разные поля разных цепочек.
 */
export type GeomData = {
  // ── броня чаши: 40 · 41 · 42 · 4i · 3 ──
  /** α₄₀ — угол якорного луча от оси дробилки, град. */
  a40: string;
  /** r₄₀ — длина якорного луча «подвес → 40», мм. */
  r40: string;
  /** β₄₀ — узловой угол в точке 40, град. */
  b40: string;
  /** l₁₁ — сегмент 40 → 41, мм. */
  l11: string;
  /** β₄₁ — узловой угол в точке 41, град. */
  b41: string;
  /** l₁₂ — сегмент 41 → 42, мм. */
  l12: string;
  /** β₄₂ — узловой угол в точке 42, град. */
  b42: string;
  /** l₁ᵢ — сегмент 42 → 4i, мм. */
  l1i: string;
  /** β₄ᵢ — узловой угол в точке 4i, град. */
  b4i: string;
  /** l₂ — сегмент 4i → 3, зона калибровки, мм. */
  l2: string;
  /** β₃ — терминальный угол брони чаши, град. */
  b3: string;

  // ── броня конуса: 10 · 11 · 12 · 1i · 2 ──
  /** α₁₀ — угол якорного луча от оси дробилки, град. */
  a10: string;
  /** r₁₀ — длина якорного луча «подвес → 10», мм. */
  r10: string;
  /** β₁₀ — узловой угол в точке 10, град. */
  b10: string;
  /** L 10 → 11, мм. */
  L10: string;
  /** β₁₁ — узловой угол в точке 11, град. */
  b11: string;
  /** L 11 → 12, мм. */
  L11: string;
  /** β₁₂ — узловой угол в точке 12, град. */
  b12: string;
  /** L 12 → 1i, мм. */
  L12: string;
  /** β₁ᵢ — узловой угол в точке 1i, град. */
  b1i: string;
  /** L 1i → 2, мм. */
  L1i: string;
  /** β₂ — терминальный угол брони конуса, град. */
  b2: string;

  // ── общее ──
  /** θ — угол качания (гирации) конуса, град. */
  theta: string;
  /** Единицы, в которых показаны и вводятся углы. */
  angleUnit: AngleUnit;

  /**
   * Целевые габариты — независимый ввод поверх построенной цепочки
   * (`applyCalibration`). В прототипе это были производные значения,
   * в визарде их задаёт пользователь.
   */
  D: string;
  H: string;
  S0: string;

  /** Число зон дробления. `l12` имеет смысл только при `'2'`. */
  zones: ZoneCount;
  /** Коэффициент R профиля камеры — из методики-источника, без отдельной формулы в этом приложении. */
  R: string;
  /** Коэффициент a профиля камеры — из методики-источника, без отдельной формулы в этом приложении. */
  a: string;
};

/** Подмножество параметров шага «Характеристический грансостав». */
export type GranData = {
  dMin: string;
  dMax: string;
  z0: string;
  s00: string;
  n0: string;
};

export type FeedType = 'dry' | 'wet';

/** Подмножество параметров шага «Грансостав продукта и усилия». */
/** Способ задания параметров формы куска. */
export type ShapeMode = 'direct' | 'sieve';

/** Строка ситовой таблицы: класс крупности вида `-0,5+0,3` и масса в граммах. */
export type SieveRowData = {
  cls: string;
  mass: string;
};

export type ProdData = {
  feedType: FeedType;
  dMin: string;
  dMax: string;
  wk: string;
  wm: string;
  kpd: string;
  /** Среднее относительное длины куска, d̄/dmax. */
  a0: string;
  /** Коэффициент вариации длины, σ/d̄. */
  va0: string;
  shapeMode: ShapeMode;
  /**
   * Ситовая таблица хранится вместе с проектом, а не живёт в состоянии
   * экрана: это введённые данные измерений, и из них выводятся a₀ и Va₀.
   * Потерять их при переходе на соседний шаг — потерять работу.
   */
  sieveRows: SieveRowData[];
};

export type WizardData = {
  geom: GeomData;
  gran: GranData;
  prod: ProdData;
};

export type StepKey = 'geom' | 'gran' | 'prod';

/**
 * Режим взаимодействия с проектом — не раздел приложения, а форма самих
 * шагов визарда. `engineering` — выбор и ввод данных, как и было всегда.
 * `simplified` — только выбор из готовых данных: дробилка(и) и проба(ы)
 * руды выбираются из каталога без ручного ввода, шаг «Продукт» даёт
 * минимум полей. Решается один раз при создании проекта — дальше форма
 * шагов зависит от этого поля, и смена режима постфактум обесценила бы
 * то, что уже введено или выбрано.
 */
export type ProjectMode = 'engineering' | 'simplified';

export type Project = {
  id: string;
  name: string;
  customer: string;
  mode: ProjectMode;
  crusherName: string;
  /** Месторождение пробы руды. Пусто, пока проба не выбрана на шаге «Грансостав». */
  ore: string;
  /**
   * Упрощённый режим: выбранные дробилки и пробы руды — их может быть
   * несколько, отчёт считает каждую комбинацию отдельно. В инженерном
   * режиме не используются: там ровно одна дробилка (`crusherName`) и
   * одна проба (`ore`).
   */
  crusherNames: string[];
  oreNames: string[];
  code: string;
  /** Метки проекта — их может быть несколько; пусто, если ни одной не поставили. */
  tags: string[];
  date: string;
  executor: string;
  oreIn: string;
  oreOut: string;
  throughput: string;
  calc: [boolean, boolean, boolean];
  /**
   * Дата и время последнего расчёта каждого шага — тот же формат, что и
   * `date` (`formatDate()`). Отдельно от `date` проекта: та не меняется
   * после создания и остаётся датой заведения проекта, а расчёт шага
   * может случиться много позже и повторно. `null`, пока шаг ни разу
   * не считался. Показывается в шторке результата.
   */
  calcDates: [string | null, string | null, string | null];
  data: WizardData;
  /**
   * Значения на момент создания проекта — опора для режима отображения
   * «Дельта» («было: X» рядом с полем, если текущее значение от него
   * отличается). В отличие от снимка на момент расчёта, доступна с самого
   * начала, а не только после первого «Выполнить расчёт»: без этого
   * переключатель «Показывать изменения» на свежем проекте не показывал
   * вообще ничего, потому что сравнивать было ещё не с чем.
   */
  initialData: WizardData;
};
