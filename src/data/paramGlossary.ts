/**
 * Границы допустимых значений для справки — берутся из того же модуля,
 * что и проверка формы (`geomLimits`), а не переписываются рядом руками:
 * иначе справка и поле однажды разойдутся, и верить будет нечему.
 */
function limitsHelp(): HelpItem[] {
  const label: Partial<Record<LimitedField, string>> = {
    b40: 'Угол чаши в зоне входа β40',
    b10: 'Углы конуса β10 · β2',
    theta: 'Угол нутации θ',
    l2: 'Длина зоны калибровки l2',
    D: 'Диаметр основания D',
    H: 'Высота H от подвеса',
    S0: 'Ширина разгрузочной щели S0',
    R: 'Коэффициент R',
    a: 'Коэффициент a',
  };

  /* Границы величин зоны — общие на все зоны, поэтому подписаны один раз
     и без номера: зон столько, сколько завёл пользователь. */
  const zoneLabel: Record<ZoneField, string> = {
    l1: 'Длина зоны дробления',
    b1: 'Угол конуса в зоне дробления',
    b4: 'Угол чаши в зоне дробления',
  };

  /* Десятичная запятая и градус вплотную к числу — как в ошибке под полем,
     чтобы справка и форма читались одинаково. */
  const num = (v: number) => String(v).replace('.', ',');
  const range = (limit: { min: number; max: number; kind: 'deg' | 'mm' | 'm' }) =>
    limit.kind === 'deg'
      ? `от ${num(limit.min)} до ${num(limit.max)}°`
      : `от ${num(limit.min)} до ${num(limit.max)} ${limit.kind === 'm' ? 'м' : 'мм'}`;

  return [
    ...(Object.keys(label) as LimitedField[]).map((field) => {
      const limit = GEOM_LIMITS[field];
      return { label: `${label[field]} — ${range(limit)}`, text: limit.why };
    }),
    ...(Object.keys(zoneLabel) as ZoneField[]).map((field) => {
      const limit = ZONE_LIMITS[field];
      return { label: `${zoneLabel[field]} — ${range(limit)}`, text: limit.why };
    }),
  ];
}

