/**
 * Профиль камеры дробления — этап 1 методики НИЛ ПАО «Уралмашзавод»
 * («Расчёт конусных дробилок КСД / КМД», §3.2 подробной документации).
 *
 * Камера — кольцевой зазор между двумя коническими поверхностями с
 * кусочно-линейными образующими. Профиль задан набором расчётных сечений
 * `i = 0…KU`, где `0` — верх камеры (вход куска), `KU = зоны + 1` — низ
 * (разгрузочная кромка). Каждая точка контура задана полярно относительно
 * точки подвеса: радиус-вектор `R` и его угол `alpha` к оси дробилки.
 *
 * Расчёт идёт **снизу вверх**, от разгрузочной кромки, где всё известно
 * из щели `S0`, габаритов `D`/`H` и длины зоны калибровки `l2`. Это и есть
 * причина, по которой профиль нельзя задать «двумя независимыми контурами
 * плюс габариты»: внешний контур (броня чаши) не вводится, а **выводится**
 * из внутреннего (броня конуса) и раскрытия камеры `S1`, которое само
 * рекурсивно раскручивается от `S0`. Прежняя реализация строила оба
 * контура независимо и потом подгоняла их под `D`/`H` неравномерным
 * масштабом — а он меняет все углы, из-за чего чертёж переставал отвечать
 * введённым `β`.
 *
 * Все углы здесь — в радианах, длины — в миллиметрах. Перевод из единиц
 * формы делает `chamberInput.ts`.
 */

/** Входные данные профиля — ровно те, что методика принимает как исходные. */
export type ChamberProfileInput = {
  /** Число зон дробления (`КоличКамер`): сечений будет `зоны + 2`. */
  zones: number;
  /** β₁₀ — угол образующей конуса в зоне входа. */
  beta10: number;
  /** β₁(i) — углы образующей конуса по зонам дробления, длиной `zones`. */
  beta1: number[];
  /** β₂ — угол образующей конуса в зоне калибровки. */
  beta2: number;
  /** β₄₀ — угол образующей чаши в зоне входа. */
  beta40: number;
  /** β₄(i) — углы образующей чаши по зонам дробления, длиной `zones`. */
  beta4: number[];
  /** l₁(i) — длины зон дробления вдоль образующей, длиной `zones`, мм. */
  l1: number[];
  /** l₂ — длина зоны калибровки ниже последнего сечения, мм. */
  l2: number;
  /** D — диаметр основания дробящего конуса, мм. */
  D: number;
  /** H — расстояние от точки подвеса до основания конуса, мм. */
  H: number;
  /** S₀ — ширина разгрузочной щели, мм. */
  S0: number;
  /** θ — угол нутации (перекос оси подвижного конуса). */
  theta: number;
};

/** Одно расчётное сечение камеры — строка таблицы профиля из отчёта этапа 1. */
export type ChamberSection = {
  /** Номер сечения: 0 — верх камеры, `KU` — разгрузочная кромка. */
  index: number;
  /** L1 — длина участка вдоль образующей до следующего сечения, мм. */
  l1: number;
  /** β₁ — угол наклона образующей брони конуса. */
  beta1: number;
  /** R1 — радиус-вектор внутреннего контура (броня конуса), мм. */
  R1: number;
  /** α₁ — угол этого радиус-вектора к оси дробилки. */
  alpha1: number;
  /** β₄ — угол наклона образующей брони чаши. */
  beta4: number;
  /** R4 — радиус-вектор внешнего контура (броня чаши), мм. */
  R4: number;
  /** α₄ — угол этого радиус-вектора к оси дробилки. */
  alpha4: number;
  /** β₄₁ — биссекторный угол «клина» между образующими. */
  beta41: number;
  /** S1 — раскрытие камеры вдоль хода эксцентрика, мм. */
  S1: number;
  /** SOT — просвет по нормали к образующим: фактический размер для куска, мм. */
  SOT: number;
  /** L сум — накопленная длина профиля от верха камеры, мм. */
  lSum: number;
};

export type ChamberProfile = {
  sections: ChamberSection[];
  /** Индекс нижнего сечения, `зоны + 1`. */
  KU: number;
  /** Пять критических углов поворота эксцентрика, по убыванию. */
  alfa: number[];
  /** Радиус-вектор и угол разгрузочной кромки. */
  R2: number;
  AL2: number;
  /** Диаметр и высота нижнего сечения — с учётом зоны калибровки. */
  DI2: number;
  H2: number;
};

/** Аргумент арксинуса за пределами [−1, 1] — накопленная погрешность, а не другой угол. */
function asinClamped(value: number): number {
  return Math.asin(Math.min(1, Math.max(-1, value)));
}

/**
 * Оригинал (`GeoM.exe`) округляет аргумент синуса до 4 знаков, и порт это
 * воспроизводит: без округления расхождение с эталонным `GEOM<N>.BI`
 * составляет 4·10⁻⁷…1,7·10⁻⁶ — выше порога чувствительности кинематики
 * (10⁻⁷), с округлением падает до машинной точности (§8.2 документации).
 */
function round4(value: number): number {
  return Math.round(value * 1e4) / 1e4;
}

/**
 * Раскладывает поля формы по сечениям `0…KU` и прогоняет девять шагов
 * методики. Возвращает то же, что оригинал кладёт в `GEOM<N>.BI` и печатает
 * таблицей отчёта этапа 1.
 */
export function computeChamberProfile(input: ChamberProfileInput): ChamberProfile {
  const NKAM = Math.max(1, Math.round(input.zones));
  const KU = NKAM + 1;
  const Q = input.theta;

  /* ── шаг 1: массивы углов и длин по сечениям ──
     Сечение 0 несёт углы зоны входа (β₁₀, β₄₀) и нулевую длину; сечения
     1…NKAM — зоны дробления; сечение KU — зона калибровки, где образующая
     чаши параллельна образующей конуса с поправкой на эксцентриситет. */
  const beta1: number[] = [input.beta10];
  const beta4: number[] = [input.beta40];
  const l1: number[] = [0];
  for (let i = 1; i <= NKAM; i += 1) {
    beta1.push(input.beta1[i - 1] ?? input.beta10);
    beta4.push(input.beta4[i - 1] ?? input.beta40);
    l1.push(input.l1[i - 1] ?? 0);
  }
  beta1.push(input.beta2);
  beta4.push(input.beta2 - Q);
  l1.push(input.l2);

  /* ── шаг 2: разгрузочная кромка ──
     Габариты D и H описывают основание дробящего конуса; нижнее расчётное
     сечение отстоит от него на длину зоны калибровки вверх по образующей,
     поэтому диаметр и высота там меньше. */
  const DI2 = input.D - 2 * input.l2 * Math.cos(input.beta2);
  const H2 = input.H - input.l2 * Math.sin(input.beta2);
  const R2 = Math.hypot(0.5 * DI2, H2);
  const AL2 = R2 > 0 ? asinClamped(DI2 / (2 * R2)) : 0;

  const R1: number[] = new Array<number>(KU + 1).fill(0);
  const alpha1: number[] = new Array<number>(KU + 1).fill(0);
  const R4: number[] = new Array<number>(KU + 1).fill(0);
  const alpha4: number[] = new Array<number>(KU + 1).fill(0);
  const beta41: number[] = new Array<number>(KU + 1).fill(0);
  const S1: number[] = new Array<number>(KU + 1).fill(0);
  const SOT: number[] = new Array<number>(KU + 1).fill(0);

  R1[KU] = R2;
  alpha1[KU] = AL2;
  S1[KU] = input.S0;

  /* ── шаг 3: обратная рекурсия внутреннего контура, снизу вверх ──
     Треугольник «радиус-вектор нижележащего сечения — длина участка —
     искомый радиус» решается теоремой косинусов, угол — теоремой синусов. */
  for (let i = NKAM; i >= 1; i -= 1) {
    const arg = round4(alpha1[i + 1] + beta1[i]);
    R1[i] = Math.sqrt(
      Math.max(0, R1[i + 1] ** 2 + l1[i] ** 2 - 2 * R1[i + 1] * l1[i] * Math.sin(arg))
    );
    alpha1[i] =
      R1[i] > 0 ? asinClamped((R1[i + 1] * Math.sin(alpha1[i + 1]) - l1[i] * Math.cos(beta1[i])) / R1[i]) : 0;
  }

  /* ── шаг 4: биссекторные углы клина ── */
  for (let i = 0; i <= KU; i += 1) beta41[i] = (beta4[i] + beta1[i] - Q) / 2;

  /* ── шаг 5: обратная рекурсия раскрытия камеры ──
     Первое слагаемое числителя — проекция нижележащего раскрытия, второе —
     вклад длины участка; знаменатель приводит результат к нормали биссектрисы. */
  for (let i = NKAM; i >= 1; i -= 1) {
    const dBeta = beta4[i] - beta1[i] + Q;
    S1[i] =
      (S1[i + 1] * Math.cos(beta4[i] - beta41[i + 1]) + l1[i] * Math.sin(dBeta)) / Math.cos(0.5 * dBeta);
  }

  /* ── шаг 6: внешний контур и просвет, сверху вниз ──
     `S1` отмеряется вдоль хода эксцентрика, `SOT` — по нормали к образующим;
     через щель кусок проходит по `SOT`, а `S1` в нижнем сечении равно `S0`. */
  const DI = -Q;
  for (let i = 1; i <= KU; i += 1) {
    R4[i] = Math.sqrt(
      Math.max(0, R1[i] ** 2 + S1[i] ** 2 - 2 * R1[i] * S1[i] * Math.cos(alpha1[i] + Q + beta41[i]))
    );
    alpha4[i] =
      R4[i] > 0 ? asinClamped((R1[i] * Math.sin(alpha1[i] + Q) + S1[i] * Math.sin(beta41[i])) / R4[i]) : 0;
    SOT[i] =
      (-R4[i] * Math.cos(beta4[i] + alpha4[i]) + R1[i] * Math.cos(beta4[i] + alpha1[i] + DI)) /
      Math.cos((beta4[i] - beta1[i] + DI) / 2);
  }

  /* ── шаг 8: верхнее сечение дублирует первое ──
     Нужно только для таблицы отчёта: собственной длины у зоны входа нет,
     она несёт лишь углы образующих β₁₀ и β₄₀. */
  R1[0] = R1[1];
  alpha1[0] = alpha1[1];
  R4[0] = R4[1];
  alpha4[0] = alpha4[1];

  /* ── шаг 7: накопительная длина ── */
  const lSum: number[] = new Array<number>(KU + 1).fill(0);
  for (let i = 1; i <= KU; i += 1) lSum[i] = lSum[i - 1] + l1[i];

  /* ── шаг 9: пять критических углов ──
     Углы радиус-векторов ключевых точек профиля плюс эксцентриситет; служат
     границами зон с разными условиями трения на этапах 2–3. */
  const R21 = Math.sqrt(
    Math.max(0, R2 ** 2 + input.l2 ** 2 + 2 * R2 * input.l2 * Math.sin(round4(AL2 + input.beta2)))
  );
  const alfa5 =
    R21 > 0
      ? asinClamped((R2 * Math.sin(AL2) + input.l2 * Math.sin(input.beta2)) / R21) + Q
      : Q;
  const alfa = [alpha4[1] + Q, alpha1[1] + Q, alpha4[KU] + Q, AL2 + Q, alfa5].sort((a, b) => b - a);

  const sections: ChamberSection[] = [];
  for (let i = 0; i <= KU; i += 1) {
    sections.push({
      index: i,
      l1: l1[i],
      beta1: beta1[i],
      R1: R1[i],
      alpha1: alpha1[i],
      beta4: beta4[i],
      R4: R4[i],
      alpha4: alpha4[i],
      beta41: beta41[i],
      S1: S1[i],
      SOT: SOT[i],
      lSum: lSum[i],
    });
  }

  return { sections, KU, alfa, R2, AL2, DI2, H2 };
}
