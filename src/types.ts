export type AngleUnit = 'deg' | 'рад';

/**
 * Одна зона дробления — тройка исходных данных методики: длина участка
 * вдоль образующей и углы обеих броней на нём.
 *
 * Длина у зоны одна на обе брони: это один и тот же участок камеры,
 * у чаши он идёт от 40 к 41, у конуса — от 10 к 11. Методика и задаёт
 * их одним массивом l₁(i).
 */
export type ZoneData = {
  /** l₁(i) — длина зоны дробления вдоль образующей, мм. */
  l1: string;
  /** β₁(i) — угол образующей брони конуса на этом участке, град. */
  b1: string;
  /** β₄(i) — угол образующей брони чаши на этом участке, град. */
  b4: string;
};

/**
 * Параметры шага «Геометрия камеры дробления» — исходные данные этапа 1
 * методики НИЛ ПАО «Уралмашзавод» (§2.2 подробной документации), ровно
 * в том наборе, который она принимает: углы образующих обеих броней по
 * зонам, длины зон, габариты основания конуса, щель и нутация.
 *
 * Радиус-векторы `r` и их углы `α` полями не являются: методика их
 * **вычисляет** (§3.2, шаги 3 и 6) и печатает в таблице профиля. Раньше
 * они стояли в форме как ввод, из-за чего профиль оказывался переопределён:
 * два контура задавались независимо и спорили с D, H и S₀, а чертёж потом
 * подгонялся под габариты неравномерным масштабом, который менял все углы.
 * Смотреть на вычисленные `r` и `α` теперь нужно в шторке результатов.
 *
 * Длины зон общие для обеих броней: зона одна, просто у чаши она идёт от
 * 40 к 41, а у конуса — от 10 к 11. Методика и задаёт их одним массивом
 * `l₁(i)`, отмеряя по образующей конуса.
 *
 * Имена полей повторяют подписи на самом чертеже: `b40` — это угол β₄₀
 * у точки 40. Зоны дробления именами не связаны — их столько, сколько
 * задал пользователь, и подписи (l₁₁, l₁₂, …) выводятся из номера зоны.
 */
export type GeomData = {
  // ── зона входа: узлы 40 и 10 ──
  /** β₄₀ — угол образующей чаши в зоне входа, град. */
  b40: string;
  /** β₁₀ — угол образующей конуса в зоне входа, град. */
  b10: string;

  /**
   * Зоны дробления по порядку, сверху вниз. Длина массива и есть число
   * зон: отдельного поля-счётчика нет, иначе оно разъезжалось бы
   * с самим набором троек — ровно это и случалось, когда число зон
   * хранилось отдельной строкой.
   */
  zones: ZoneData[];

  // ── зона калибровки: последний узел → 3 / 2 ──
  /** l₂ — длина зоны калибровки, мм. */
  l2: string;
  /** β₂ — угол образующей конуса в зоне калибровки, град. */
  b2: string;

  // ── общее ──
  /** θ — угол нутации конуса, град. */
  theta: string;
  /** Единицы, в которых показаны и вводятся углы. */
  angleUnit: AngleUnit;

  /**
   * Габариты основания дробящего конуса и разгрузочная щель. В методике
   * это полноценные исходные данные: от них рекурсия раскручивает весь
   * профиль снизу вверх (§3.2), а не подгоняет под них уже построенный.
   */
  D: string;
  H: string;
  S0: string;

  /** Коэффициент R профиля камеры — плечо приведения усилий, этап 3. */
  R: string;
  /** Коэффициент a профиля камеры — плечо до точки опрокидывания, этап 3. */
  a: string;
};

/** Способ задания параметров формы куска. */
export type ShapeMode = 'direct' | 'sieve';

/**
 * Что вводит пользователь в ситовой таблице — остальные две величины
 * пересчитываются из неё: «по минусу» и «по плюсу» дополняют друг друга
 * до 100 %, «частные классы» — их разность по соседним классам.
 */
export type SieveInputMode = 'minus' | 'plus' | 'classes';

/** Строка ситовой таблицы: класс крупности вида `-0,5+0,3` и введённое значение (смысл — в `SieveInputMode` таблицы). */
export type SieveRowData = {
  cls: string;
  value: string;
};

/** Подмножество параметров шага «Характеристический грансостав». */
export type GranData = {
  dMin: string;
  /**
   * Dk — кондиционная крупность питания, мм. Стоит между `dMin` и `dMax`
   * в исходных данных методики-источника (`DMIN=15, DK=15, DMAX=70`) — был
   * пропущен при переносе тринадцати полей формы, хотя присутствует
   * в примере расчёта наравне с остальными границами крупности.
   */
  dk: string;
  dMax: string;
  z0: string;
  s00: string;
  n0: string;
  /** Среднее относительное длины куска, d̄/dmax. */
  a0: string;
  /** Коэффициент вариации длины, σ/d̄. */
  va0: string;
  shapeMode: ShapeMode;
  /** Какая колонка ситовой таблицы сейчас — ввод, а какие две — пересчёт. */
  sieveMode: SieveInputMode;
  /**
   * Ситовая таблица хранится вместе с проектом, а не живёт в состоянии
   * экрана: это введённые данные измерений, и из них выводятся a₀ и Va₀.
   * Потерять их при переходе на соседний шаг — потерять работу.
   *
   * Параметры формы куска перенесены сюда, на «Грансостав», с «Продукта»
   * (было до версии 15 хранилища проектов) — они характеризуют кусок
   * питания, а не продукта дробления.
   */
  sieveRows: SieveRowData[];
};

export type FeedType = 'dry' | 'wet';

export type ProdData = {
  feedType: FeedType;
  dMin: string;
  dMax: string;
  wk: string;
  wm: string;
  kpd: string;
};

export type WizardData = {
  geom: GeomData;
  gran: GranData;
  prod: ProdData;
};

export type StepKey = 'geom' | 'gran' | 'prod';

/**
 * Режим взаимодействия с проектом — не раздел приложения, а форма самих
 * шагов визарда. `engineering` — выбор и ввод данных, как и было всегда.
 * `simplified` — только выбор из готовых данных: дробилка(и) и проба(ы)
 * руды выбираются из каталога без ручного ввода, шаг «Продукт» даёт
 * минимум полей. Решается один раз при создании проекта — дальше форма
 * шагов зависит от этого поля, и смена режима постфактум обесценила бы
 * то, что уже введено или выбрано.
 */
export type ProjectMode = 'engineering' | 'simplified';

export type Project = {
  id: string;
  name: string;
  customer: string;
  mode: ProjectMode;
  crusherName: string;
  /** Месторождение пробы руды. Пусто, пока проба не выбрана на шаге «Грансостав». */
  ore: string;
  /**
   * Упрощённый режим: выбранные дробилки и пробы руды — их может быть
   * несколько, отчёт считает каждую комбинацию отдельно. В инженерном
   * режиме не используются: там ровно одна дробилка (`crusherName`) и
   * одна проба (`ore`).
   */
  crusherNames: string[];
  oreNames: string[];
  code: string;
  /** Метки проекта — их может быть несколько; пусто, если ни одной не поставили. */
  tags: string[];
  date: string;
  executor: string;
  oreIn: string;
  oreOut: string;
  throughput: string;
  calc: [boolean, boolean, boolean];
  /**
   * Дата и время последнего расчёта каждого шага — тот же формат, что и
   * `date` (`formatDate()`). Отдельно от `date` проекта: та не меняется
   * после создания и остаётся датой заведения проекта, а расчёт шага
   * может случиться много позже и повторно. `null`, пока шаг ни разу
   * не считался. Показывается в шторке результата.
   */
  calcDates: [string | null, string | null, string | null];
  /**
   * Слепок данных шага на момент его последнего расчёта — по нему видно,
   * разошлись ли текущие значения с тем, что легло в уже посчитанный
   * результат. Не то же самое, что `initialData` ниже: та хранит момент
   * создания проекта и не обновляется при пересчёте, а это поле — момент
   * именно расчёта. `null`, пока шаг ни разу не считался.
   */
  calcSnapshot: [GeomData | null, GranData | null, ProdData | null];
  data: WizardData;
  /**
   * Значения на момент создания проекта — опора для режима отображения
   * «Дельта» («было: X» рядом с полем, если текущее значение от него
   * отличается). В отличие от снимка на момент расчёта, доступна с самого
   * начала, а не только после первого «Выполнить расчёт»: без этого
   * переключатель «Показывать изменения» на свежем проекте не показывал
   * вообще ничего, потому что сравнивать было ещё не с чем.
   */
  initialData: WizardData;
};
