import { useEffect } from 'react';

/**
 * Esc закрывает только верхнее окно.
 *
 * Подпорка под дефект дизайн-системы: `Modal` не проверяет, верхний ли он
 * слой. Каждое окно вешает свой обработчик Esc на `document` в фазе
 * всплытия, и порядок срабатывания у них — порядок подписки, то есть
 * порядок монтирования: внешнее окно смонтировано раньше и закрывается
 * первым. Нажатие Esc во вложенном окне уносило вместе с ним и внешнее —
 * а с ним весь незавершённый выбор.
 *
 * Перехват идёт на погружении: обработчик на `document` в фазе capture
 * срабатывает раньше любых всплывающих на том же узле, поэтому здесь
 * событие можно остановить и закрыть ровно то окно, которое сверху.
 * Своё закрытие приходится делать руками — остановленное событие не дойдёт
 * и до собственного обработчика вложенного окна.
 *
 * Заявка в систему — отдельно; чинить это надо там, а не здесь.
 *
 * @param active Окно открыто и сейчас оно верхнее.
 * @param onEscape Что считать закрытием: обычно тот же путь, что у крестика.
 */
export function useTopEscape(active: boolean, onEscape: () => void) {
  useEffect(() => {
    if (!active) return;

    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key !== 'Escape') return;
      event.stopPropagation();
      onEscape();
    };

    document.addEventListener('keydown', onKeyDown, true);
    return () => document.removeEventListener('keydown', onKeyDown, true);
  }, [active, onEscape]);
}
